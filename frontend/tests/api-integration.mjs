import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { NeighborrowApi, ApiError } = await import(pathToFileURL(process.env.API_CLIENT_MODULE));
const base = process.env.TEST_API_URL;
const owner = new NeighborrowApi(base), neighbor = new NeighborrowApi(base);
const outsider = new NeighborrowApi(base), guest = new NeighborrowApi(base);
const password = 'Integration-Safe-Pass-931!';
const register = (api, name) => api.register({ email: `${name}@example.com`, password, password_repeat: password, first_name: name, last_name: 'Neighbor' });
await register(owner, 'owner'); await register(neighbor, 'neighbor'); await register(outsider, 'outsider');
await owner.login('owner@example.com', password);
await neighbor.login('neighbor@example.com', password);
await outsider.login('outsider@example.com', password);
assert.equal((await owner.request('/auth/me')).is_resident_verified, false);
await assert.rejects(owner.request('/listings'), e => e instanceof ApiError && e.status === 403);
const complexes = await owner.request('/auth/residential-complexes');
const complexA = complexes.find(c => c.name === 'Integration Complex A');
const complexB = complexes.find(c => c.name === 'Integration Complex B');
assert(complexA && complexB);
assert.equal(complexA.code_hash, undefined);
await assert.rejects(owner.verifyResidence(complexA.id, process.env.TEST_COMPLEX_B_CODE), e => e.status === 400);
assert.equal((await owner.request('/auth/me')).is_resident_verified, false);
assert.equal((await owner.verifyResidence(complexA.id, process.env.TEST_COMPLEX_A_CODE)).is_resident_verified, true);
await neighbor.verifyResidence(complexA.id, process.env.TEST_COMPLEX_A_CODE);
await outsider.verifyResidence(complexB.id, process.env.TEST_COMPLEX_B_CODE);
await assert.rejects(owner.verifyResidence(complexB.id, process.env.TEST_COMPLEX_A_CODE), e => e.status === 400);
const categories = await guest.request('/categories'); assert.equal(categories.length, 6);
const tools = categories.find(c => c.slug === 'tools');
const payload = { type: 'offer', title: 'Integration hammer', description: 'For hanging shelves', category: tools.id, condition: 'good', duration: '2 hours', contact_phone: '+77001234567', contact_social: 'https://example.com/owner', latitude: 43.25, longitude: 76.95 };
const offer = await owner.request('/listings', { method: 'POST', body: payload });
const request = await neighbor.request('/listings', { method: 'POST', body: { ...payload, type: 'request', title: 'Need hammer', contact_phone: '' } });
const otherOffer = await outsider.request('/listings', { method: 'POST', body: { ...payload, title: 'Other complex hammer' } });
assert.equal(offer.mine, true); assert.equal(offer.owner.display_name, 'owner N.');
await assert.rejects(guest.request('/listings'), e => e.status === 401);
const feed = await neighbor.request('/listings?type=offer&search=hammer'); assert.equal(feed.count, 1);
assert.equal(feed.results[0].contact_phone, undefined);
const nearby = await neighbor.request('/listings?latitude=43.25&longitude=76.95&radius_km=1&ordering=nearest'); assert.equal(nearby.count, 2);
await assert.rejects(neighbor.request(`/listings/${otherOffer.id}`), e => e.status === 404);
await assert.rejects(neighbor.request(`/listings/${otherOffer.id}/contacts`), e => e.status === 404);
await assert.rejects(neighbor.request(`/listings/${otherOffer.id}/matches`), e => e.status === 404);
await assert.rejects(neighbor.request(`/listings/${otherOffer.id}/interest`, { method: 'POST' }), e => e.status === 404);
await assert.rejects(guest.request(`/listings/${offer.id}/contacts`), e => e instanceof ApiError && e.status === 401);
await assert.rejects(neighbor.request(`/listings/${offer.id}`, { method: 'PATCH', body: { title: 'Not mine' } }), e => e.status === 403);
const matches = await neighbor.request(`/listings/${request.id}/matches`); assert.equal(matches.results[0].id, offer.id);
const interest = await neighbor.request(`/listings/${offer.id}/interest`, { method: 'POST' }); assert.equal(interest.created, true);
assert.equal((await neighbor.request(`/listings/${offer.id}/interest`, { method: 'POST' })).created, false);
assert.equal((await neighbor.request(`/listings/${offer.id}`)).has_responded, true);
const contacts = await neighbor.request(`/listings/${offer.id}/contacts`); assert.equal(contacts.phone, payload.contact_phone);
assert((await owner.request('/activity')).results.some(a => a.type === 'offer_requested'));
await owner.updateProfile({ first_name: 'Updated', address: 'Almaly, Almaty' });
assert.equal((await owner.verifyResidence(complexB.id, process.env.TEST_COMPLEX_B_CODE)).residential_complex.id, complexB.id);
await assert.rejects(owner.request(`/listings/${offer.id}`), e => e.status === 404);
await assert.rejects(neighbor.request(`/listings/${offer.id}`), e => e.status === 404);
await assert.rejects(neighbor.request(`/listings/${offer.id}/contacts`), e => e.status === 404);
const movedOffer = await owner.request('/listings', { method: 'POST', body: { ...payload, title: 'New complex hammer' } });
assert((await outsider.request('/listings')).results.some(item => item.id === movedOffer.id));
await assert.rejects(neighbor.request(`/listings/${movedOffer.id}`), e => e.status === 404);
await owner.logout();
// A fresh client models a page reload: stored records remain after another login.
const reloaded = new NeighborrowApi(base); await reloaded.login('owner@example.com', password);
assert.equal((await reloaded.request('/auth/me')).first_name, 'Updated');
assert.equal((await reloaded.request('/listings?mine=true')).count, 1);
await reloaded.request(`/listings/${movedOffer.id}`, { method: 'PATCH', body: { available: false } });
assert.equal((await neighbor.request(`/listings/${request.id}/matches`)).count, 0);
await reloaded.changePassword(password, 'Updated-Integration-Pass-842!', 'Updated-Integration-Pass-842!');
await assert.rejects(reloaded.request('/auth/me'), e => e.status === 401);
await reloaded.login('owner@example.com', 'Updated-Integration-Pass-842!');
await reloaded.deleteAccount('Updated-Integration-Pass-842!');
await assert.rejects(neighbor.request(`/listings/${offer.id}`), e => e.status === 404);
await neighbor.request(`/listings/${request.id}`, { method: 'DELETE' });
await neighbor.logout();
assert.equal((await outsider.request('/listings')).count, 1);
assert.equal((await outsider.request(`/listings/${otherOffer.id}`)).id, otherOffer.id);
console.log('PASS: residence verification, two-complex isolation, listings, contacts, matching, response, activity, profile and account lifecycle.');
